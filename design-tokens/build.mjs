#!/usr/bin/env node
// Generates platform token files from motion-tokens.json (the single source of truth):
//   color-tokens.json  Material You light/dark schemes from the CrossWay seed colour
//   tokens.ts          TypeScript constants for the React and React Native apps
//   tokens.css         CSS custom properties (light + dark) for the web apps
//   MotionTokens.kt    Jetpack Compose constants for a native Android build
// Usage: node design-tokens/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  argbFromHex, hexFromArgb, Hct, MaterialDynamicColors, SchemeFidelity, TonalPalette,
} from '@material/material-color-utilities';

const dir = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(dir, 'motion-tokens.json'), 'utf8'));
const HEADER = 'GENERATED by design-tokens/build.mjs from motion-tokens.json. Do not edit by hand.';

/* ---------------- springs ---------------- */
// Convert a damping ratio to the damping coefficient used by Motion, React Native
// Animated and Reanimated (all take stiffness/damping/mass): c = ζ · 2√(k·m).
const springs = {};
for (const [scheme, groups] of Object.entries(src.springs)) {
  if (scheme.startsWith('_')) continue;
  springs[scheme] = {};
  for (const [kind, speeds] of Object.entries(groups)) {
    springs[scheme][kind] = {};
    for (const [speed, { dampingRatio, stiffness }] of Object.entries(speeds)) {
      const damping = +(dampingRatio * 2 * Math.sqrt(stiffness)).toFixed(2);
      springs[scheme][kind][speed] = { dampingRatio, stiffness, damping, mass: 1 };
    }
  }
}

/* ---------------- colour ---------------- */
const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'inverseSurface', 'inverseOnSurface',
  'outline', 'outlineVariant', 'shadow', 'scrim',
];
const seed = Hct.fromInt(argbFromHex(src.color.seed));
const custom = (hex, dark) => {
  const p = TonalPalette.fromInt(argbFromHex(hex));
  const t = dark ? { c: 80, on: 20, cont: 30, onCont: 90 } : { c: 40, on: 100, cont: 90, onCont: 10 };
  return { color: hexFromArgb(p.tone(t.c)), on: hexFromArgb(p.tone(t.on)), container: hexFromArgb(p.tone(t.cont)), onContainer: hexFromArgb(p.tone(t.onCont)) };
};
const colors = {};
for (const mode of ['light', 'dark']) {
  const scheme = new SchemeFidelity(seed, mode === 'dark', 0);
  const c = {};
  for (const r of ROLES) c[r] = hexFromArgb(MaterialDynamicColors[r].getArgb(scheme)).toUpperCase();
  for (const [name, hex] of Object.entries(src.color.custom)) {
    const v = custom(hex, mode === 'dark');
    const cap = name[0].toUpperCase() + name.slice(1);
    c[name] = v.color.toUpperCase();
    c['on' + cap] = v.on.toUpperCase();
    c[name + 'Container'] = v.container.toUpperCase();
    c['on' + cap + 'Container'] = v.onContainer.toUpperCase();
  }
  colors[mode] = c;
}

const tokens = {
  version: src.version,
  springs,
  schemeByProduct: Object.fromEntries(Object.entries(src.schemeByProduct).filter(([k]) => !k.startsWith('_'))),
  duration: { short: src.duration.short.value, medium: src.duration.medium.value, long: src.duration.long.value, adminMax: src.duration.adminMax },
  easing: src.easing,
  stagger: src.stagger,
  shape: { corner: src.shape.corner, morph: { ...src.shape.morph, _note: undefined } },
  color: { seed: src.color.seed, brand: src.color.brand, ...colors },
  accessibility: src.accessibility,
};
delete tokens.shape.morph._note;

writeFileSync(join(dir, 'color-tokens.json'), JSON.stringify({ $comment: HEADER, seed: src.color.seed, ...colors }, null, 2) + '\n');

/* ---------------- TypeScript ---------------- */
writeFileSync(
  join(dir, 'tokens.ts'),
  `// ${HEADER}
/* eslint-disable */
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

export type MotionSchemeName = keyof typeof tokens.springs;
export type SpringKind = 'spatial' | 'effects';
export type SpringSpeed = 'fast' | 'default' | 'slow';
export type ShapeName = keyof typeof tokens.shape.morph.targets;
export type ColorRole = keyof typeof tokens.color.light;

/** Spring parameters ({ stiffness, damping, mass }) for Motion, RN Animated or Reanimated. */
export function spring(scheme: MotionSchemeName, kind: SpringKind, speed: SpringSpeed = 'default') {
  const s = tokens.springs[scheme][kind][speed];
  return { stiffness: s.stiffness, damping: s.damping, mass: s.mass };
}

/** CSS cubic-bezier() for a fallback easing token. */
export const cssEasing = (name: keyof typeof tokens.easing) => \`cubic-bezier(\${tokens.easing[name].join(', ')})\`;

/** Delay for the i-th item of a staggered list, capped at stagger.maxItems. */
export const staggerDelay = (i: number, interval: number = tokens.stagger.interval) =>
  Math.min(i, tokens.stagger.maxItems - 1) * interval;
`,
);

/* ---------------- CSS ---------------- */
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());
const vars = c => Object.entries(c).map(([k, v]) => `  --md-sys-color-${kebab(k)}: ${v};`).join('\n');
const motionVars = [
  ...Object.entries(tokens.duration).map(([k, v]) => `  --md-motion-duration-${kebab(k)}: ${v}ms;`),
  ...Object.entries(src.easing).map(([k, v]) => `  --md-motion-easing-${kebab(k)}: cubic-bezier(${v.join(', ')});`),
  `  --md-motion-stagger: ${src.stagger.interval}ms;`,
  ...Object.entries(src.shape.corner).map(([k, v]) => `  --md-shape-corner-${kebab(k)}: ${v}px;`),
].join('\n');
writeFileSync(
  join(dir, 'tokens.css'),
  `/* ${HEADER} */
:root {
  color-scheme: light;
${vars(colors.light)}
${motionVars}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${vars(colors.dark).replace(/^ {2}/gm, '    ')}
  }
}
:root[data-theme='dark'] {
  color-scheme: dark;
${vars(colors.dark)}
}
`,
);

/* ---------------- Kotlin (Jetpack Compose) ---------------- */
const pascal = s => s[0].toUpperCase() + s.slice(1);
const kColor = hex => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const kt = [];
kt.push(`// ${HEADER}`, 'package com.crossway.design', '', 'import androidx.compose.animation.core.FiniteAnimationSpec', 'import androidx.compose.animation.core.spring', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', '');
kt.push('object CrossWayMotion {');
for (const [scheme, groups] of Object.entries(springs))
  for (const [kind, speeds] of Object.entries(groups))
    for (const [speed, s] of Object.entries(speeds))
      kt.push(`    fun <T> ${scheme}${pascal(speed)}${pascal(kind)}(): FiniteAnimationSpec<T> = spring(dampingRatio = ${s.dampingRatio}f, stiffness = ${s.stiffness}f)`);
kt.push('');
for (const [k, v] of Object.entries(tokens.duration)) kt.push(`    const val Duration${pascal(k)}Ms = ${v}`);
kt.push(`    const val StaggerMs = ${src.stagger.interval}`, `    const val StaggerMaxItems = ${src.stagger.maxItems}`, '}', '');
kt.push('object CrossWayShape {');
for (const [k, v] of Object.entries(src.shape.corner)) kt.push(`    val ${k} = ${v === 9999 ? '50' : v}${v === 9999 ? ' // percent' : '.dp'}`);
kt.push('}', '');
for (const mode of ['light', 'dark']) {
  kt.push(`object CrossWay${pascal(mode)}Colors {`);
  for (const [k, v] of Object.entries(colors[mode])) kt.push(`    val ${k} = ${kColor(v)}`);
  kt.push('}', '');
}
writeFileSync(join(dir, 'MotionTokens.kt'), kt.join('\n'));

console.log('design tokens generated: color-tokens.json, tokens.ts, tokens.css, MotionTokens.kt');
